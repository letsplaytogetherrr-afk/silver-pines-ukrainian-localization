[CmdletBinding()]
param(
    [Parameter(Mandatory=$true)][string]$GameDirectory,
    [Parameter(Mandatory=$true)][string]$CompilerPath,
    [string]$LoaderDirectory,
    [string]$OutputDirectory
)
$ErrorActionPreference = 'Stop'
$repoRoot = $PSScriptRoot
if (-not $LoaderDirectory) { $LoaderDirectory = $GameDirectory }
if (-not $OutputDirectory) { $OutputDirectory = Join-Path $repoRoot 'artifacts' }
$interop = Join-Path $GameDirectory 'BepInEx/interop'
$core = Join-Path $LoaderDirectory 'BepInEx/core'
$runtime = Join-Path $LoaderDirectory 'dotnet'
foreach ($directory in @($interop, $core, $runtime)) {
    if (-not (Test-Path -LiteralPath $directory -PathType Container)) {
        throw "Missing dependency directory: $directory. Follow BUILD.md; interop assemblies are generated by BepInEx from a locally owned game."
    }
}
if (-not (Test-Path -LiteralPath $CompilerPath -PathType Leaf)) { throw 'CompilerPath must point to Roslyn tasks/net472/csc.exe.' }
$refs = @()
foreach ($directory in @($runtime, $interop, $core)) {
    foreach ($file in (Get-ChildItem -LiteralPath $directory -Filter '*.dll' -File | Sort-Object Name)) {
        # Never pass native DLLs such as coreclr.dll or dobby.dll as C# references.
        try { [void][Reflection.AssemblyName]::GetAssemblyName($file.FullName); $refs += $file.FullName } catch { }
    }
}
foreach ($required in @('BepInEx.Unity.IL2CPP.dll','CarpenterScripts.dll','Unity.Localization.dll','Unity.TextMeshPro.dll')) {
    if (-not ($refs | Where-Object { [IO.Path]::GetFileName($_) -eq $required })) { throw "Missing managed reference: $required" }
}
[void][IO.Directory]::CreateDirectory($OutputDirectory)
$output = Join-Path $OutputDirectory 'SilverPinesLocalization.dll'
$source = Join-Path $repoRoot 'src/LocalizationPlugin.cs'
$options = @('/nologo','/target:library','/nostdlib+','/langversion:latest',('/out:' + $output))
$options += @($refs | ForEach-Object { '/reference:' + $_ })
$options += $source
$response = Join-Path $OutputDirectory 'build.rsp'
$options | ForEach-Object { '"' + $_ + '"' } | Set-Content -LiteralPath $response -Encoding utf8
& $CompilerPath ('@' + $response)
if ($LASTEXITCODE -ne 0) { throw 'Plugin compilation failed.' }
Write-Output ('Built: ' + $output)
Get-FileHash -LiteralPath $output -Algorithm SHA256 | Select-Object Algorithm,Hash,Path
# Deliberately no copy into the game, game launch, download, or process termination.
